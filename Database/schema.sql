CREATE TABLE Authors(
    Id INT IDENTITY (1,1) PRIMARY KEY,
    Name NVARCHAR (100) NOT NULL,
    Bio NVARCHAR (500) NULL
);

CREATE TABLE Categories(
    Id INT IDENTITY (1,1) PRIMARY KEY,
    Name NVARCHAR(100) UNIQUE NOT NULL
);

CREATE TABLE Books(
    Id INT IDENTITY (1,1) PRIMARY KEY,
    Title NVARCHAR(100) NOT NULL,
    AuthorId INT NOT NULL REFERENCES Authors(Id),
    CategoryId INT NOT NULL REFERENCES Categories(Id),
    TotalCopies INT NOT NULL CHECK(TotalCopies >= 0)
);

CREATE TABLE Members(
    Id INT IDENTITY(1,1) PRIMARY KEY,
    Name NVARCHAR(100) NOT NULL,
    Email NVARCHAR(256) UNIQUE NOT NULL
);

CREATE TABLE Loans(
    Id INT IDENTITY(1,1) PRIMARY KEY,
    MemberId INT NOT NULL REFERENCES Members(Id),
    BookId INT NOT NULL REFERENCES Books(Id),
    BorrowedAt DATETIME2 NOT NULL DEFAULT SYSUTCDATETIME(),
    DueAt DATETIME2 NOT NULL ,
    ReturnedAt DATETIME2 NULL,
    CHECK(DueAt > BorrowedAt)
);

